"""The DI-1 synthetic corpus: fictional service agreements and structural edge cases.

Every organisation, person and amount is invented. `dev` cases may be used
while building extractors; `heldout` cases are written before any extractor
exists and must never be used for tuning (EVALS.md). `heldout-2` (AI1) is a
second held-out split, written from the frozen contract in predeclared
coverage categories and pre-registered (corpus/eval/heldout-2-preregistration.md)
before any model-assisted extractor exists; it must never be used to write or
tune a prompt, a model configuration or a rule. `heldout-3` and `assist-dev`
(AI1, assisted-2) are generated by generated.py from the frozen specification
corpus/eval/heldout-3-spec.json: heldout-3 is pre-registered and never used for
development; assist-dev is for development only. Parse expectations live
in corpus/expected/parse/; extraction expectations are added with the
extractor (DI-1 PR 2).
"""

