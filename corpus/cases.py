def _truncated() -> bytes:
    data = build(Document((LABELLED,)))
    return data[: len(data) * 6 // 10]


def _many_pages() -> bytes:
    pages = tuple(text_page(f"Synthetic filler page {n}.") for n in range(1, 102))
    return build(Document(pages))


